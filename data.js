// ========== 时段判断函数 ==========
// 判断某个时间点是否在限行时段内
function isInRestrictedPeriod(timeMinutes, timeRule, vehicleType) {
  // timeMinutes: 0-1440 分钟数
  // timeRule: 时间规则描述
  
  // 重型货车核心区：全天禁止（环路内 0:00-8:00 允许）
  if (timeRule.includes('全天禁止')) {
    if (timeMinutes >= 0 && timeMinutes < 480) {
      return { restricted: false, reason: '环路内 0:00-8:00 允许通行' };
    }
    return { restricted: true, reason: '全天限行' };
  }
  
  // 重型货车中心区、中型货车：8:00-24:00 限行
  if (timeRule.includes('8:00-24:00 限行') && !timeRule.includes('12:00')) {
    if (timeMinutes >= 480 && timeMinutes <= 1440) {
      return { restricted: true, reason: '8:00-24:00 限行' };
    }
    return { restricted: false, reason: '允许通行时段' };
  }
  
  // 轻型货车区域：早晚高峰限行
  if (timeRule.includes('早晚高峰')) {
    // 工作日 8:30-10:30 (510-630), 18:30-20:30 (1110-1230)
    if ((timeMinutes >= 510 && timeMinutes <= 630) || 
        (timeMinutes >= 1110 && timeMinutes <= 1230)) {
      return { restricted: true, reason: '早晚高峰限行' };
    }
    return { restricted: false, reason: '非高峰时段允许通行' };
  }
  
  // 轻型货车路段：8:00-22:00 限行
  if (timeRule.includes('8:00-22:00')) {
    if (timeMinutes >= 480 && timeMinutes <= 1320) {
      return { restricted: true, reason: '8:00-22:00 限行' };
    }
    return { restricted: false, reason: '允许通行时段' };
  }
  
  // 货运通道：8:00-12:00, 17:00-24:00 限行（其余时段允许）
  if (timeRule.includes('17:00-24:00') || timeRule.includes('12:00')) {
    if ((timeMinutes >= 480 && timeMinutes <= 720) || 
        (timeMinutes >= 1020 && timeMinutes <= 1440)) {
      return { restricted: true, reason: '货运通道限行时段' };
    }
    return { restricted: false, reason: '货运通道允许通行时段' };
  }
  
  return { restricted: false, reason: '' };
}

